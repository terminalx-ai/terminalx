//! Private per-guest key lifecycle. No import-from-path API, host key discovery,
//! agent lookup occurs. The fixed OpenSSH producer runs only behind an
//! authenticated gate: the post-trust transport binding (still closed), or a
//! version-3 owner's enrolled VM and helper-acknowledged, person-confirmed
//! account (`macos_owner_channel::grant_guest_key`). Tests use synthetic utilities.
use super::{
    journal,
    macos_transport::{self, Binding},
};
use anyhow::{bail, Context, Result};
use serde_json::{json, Value};
use std::{
    io::{Read, Write},
    os::{
        fd::AsRawFd,
        unix::fs::{MetadataExt, OpenOptionsExt},
    },
    path::{Path, PathBuf},
    time::Duration,
};

pub(super) fn check_directory(path: &Path) -> Result<()> {
    let metadata = std::fs::symlink_metadata(path)?;
    // SAFETY: geteuid has no arguments or memory preconditions.
    if !metadata.is_dir()
        || metadata.uid() != unsafe { libc::geteuid() }
        || metadata.mode() & 0o077 != 0
    {
        bail!("Transport storage must be an owned private directory without symlinks");
    }
    Ok(())
}
pub(super) fn private_read(path: &Path, bound: u64) -> Result<Vec<u8>> {
    let file = std::fs::OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK)
        .open(path)?;
    let metadata = file.metadata()?;
    // SAFETY: geteuid has no arguments or memory preconditions.
    if !metadata.is_file()
        || metadata.nlink() != 1
        || metadata.uid() != unsafe { libc::geteuid() }
        || metadata.mode() & 0o077 != 0
    {
        bail!("Transport reference is not an owned private regular file");
    }
    let mut bytes = Vec::new();
    file.take(bound + 1).read_to_end(&mut bytes)?;
    if bytes.len() as u64 > bound {
        bail!("Private transport reference exceeds its bound");
    }
    Ok(bytes)
}
pub(super) fn write_new(path: &Path, bytes: &[u8]) -> Result<()> {
    check_directory(path.parent().context("Private reference parent missing")?)?;
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(path)?;
    file.write_all(bytes)?;
    file.sync_all()?;
    std::fs::File::open(path.parent().unwrap())?.sync_all()?;
    Ok(())
}
fn directory(root: &Path, binding: &Binding) -> Result<PathBuf> {
    reference_directory(root, &binding.key_reference)
}
fn reference_directory(root: &Path, key_reference: &str) -> Result<PathBuf> {
    journal::validate_id(key_reference)?;
    Ok(root.join("macos-personalization-keys").join(key_reference))
}
fn lock(path: &Path) -> Result<std::fs::File> {
    check_directory(path)?;
    let lock = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(false)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(path.join("operation.lock"))?;
    // lock owns its descriptor for the full preparation/RPC lifetime.
    if !crate::local_vm::journal::try_exclusive(&lock)? {
        bail!("Guest key reference is in use");
    }
    Ok(lock)
}
/// An immutable binding as a record holds it: its JSON and the digest of the
/// bytes it was serialized from, so each binding type keeps its own encoding.
pub(super) struct Bound {
    value: Value,
    digest: String,
}
impl Bound {
    pub(super) fn of(binding: &impl serde::Serialize) -> Result<Self> {
        Ok(Self { value: serde_json::to_value(binding)?, digest: journal::digest(&serde_json::to_vec(binding)?) })
    }
    fn record(&self, state: &str) -> Value {
        json!({"binding":self.value,"inputDigest":self.digest,"state":state,"producer":PRODUCER})
    }
}
fn read(path: &Path, binding: &Binding) -> Result<Value> {
    read_bound(path, &Bound::of(binding)?)
}
fn read_bound(path: &Path, bound: &Bound) -> Result<Value> {
    let record: Value =
        serde_json::from_slice(&private_read(&path.join("record.json"), 32 * 1024)?)?;
    if record["binding"] != bound.value || record["inputDigest"] != bound.digest.as_str() {
        bail!("Per-guest key reference belongs to another immutable binding");
    }
    Ok(record)
}
fn retain(path: &Path, value: &Value) -> Result<()> {
    journal::atomic_private_write(&path.join("record.json"), &serde_json::to_vec(value)?)
}

/// Generated bytes are kept out of JSON, argv, logs and artifacts. A producer
/// takes no host credential path. No production source invokes this boundary.
#[allow(dead_code)] // Synthetic fixtures only until an authenticated provisioning producer exists.
pub(super) struct GeneratedKey {
    pub private: zeroize::Zeroizing<Vec<u8>>,
    pub public: String,
}
#[allow(dead_code)] // Intentionally not exposed as an import/generate control RPC.
pub(super) fn prepare_using(
    root: &Path,
    binding: &Binding,
    verifier: &Path,
    producer: impl FnOnce() -> Result<GeneratedKey>,
) -> Result<Value> {
    binding.check_retained(root)?;
    check_directory(root)?;
    let parent = root.join("macos-personalization-keys");
    if !parent.try_exists()? {
        std::fs::DirBuilder::new().mode(0o700).create(&parent)?;
    }
    check_directory(&parent)?;
    let path = directory(root, binding)?;
    if path.try_exists()? {
        let _lock = lock(&path)?;
        // Unknown, retired and ready records are observation only, not replay.
        return read(&path, binding);
    }
    std::fs::DirBuilder::new().mode(0o700).create(&path)?;
    let _lock = lock(&path)?;
    let mut record = json!({"binding":binding,"inputDigest":journal::digest(&serde_json::to_vec(binding)?),"state":"outcomeUnknown"});
    retain(&path, &record)?;
    let generated = producer()?;
    super::macos_personalization::public_key(&generated.public)?;
    if generated.private.is_empty() || generated.private.len() > 16 * 1024 {
        bail!("Generated key exceeds its bound");
    }
    let private = path.join("private_key");
    write_new(&private, &generated.private)?;
    let public = derive(verifier, &private, Duration::from_secs(15))?;
    if public != generated.public {
        bail!("Generated private/public key pairing differs");
    }
    let metadata = std::fs::symlink_metadata(&private)?;
    record["receipt"] = json!({"publicKey":public,"privateSha256":journal::digest(&generated.private),"device":metadata.dev(),"inode":metadata.ino()});
    record["state"] = json!("ready");
    retain(&path, &record)?;
    Ok(record)
}
use std::os::unix::fs::DirBuilderExt;

fn derive(program: &Path, private: &Path, budget: Duration) -> Result<String> {
    let bytes = super::process::run(
        macos_transport::isolated(program, private.parent().unwrap())
            .args(["-y", "-f"])
            .arg(private),
        b"",
        budget,
    )?;
    let public = std::str::from_utf8(&bytes)?.trim().to_string();
    super::macos_personalization::public_key(&public)?;
    Ok(public)
}
pub(super) fn resolve(
    root: &Path,
    binding: &Binding,
    verifier: &Path,
    budget: Duration,
) -> Result<std::fs::File> {
    binding.check_retained(root)?;
    let bound = transport_bound(root, binding)?;
    Ok(resolve_in(root, &binding.key_reference, &bound, verifier, budget)?.0)
}
/// The binding this reference's record must hold for the transport: the
/// transport binding itself, or the version-3 key produced for exactly this
/// reference, bootstrap, VM and account, whose helper-acknowledged answer is the
/// evidence behind the ledger's account receipt. Anything else stays refused.
fn transport_bound(root: &Path, binding: &Binding) -> Result<Bound> {
    let path = directory(root, binding)?;
    let record: Value = serde_json::from_slice(&private_read(&path.join("record.json"), 32 * 1024)?)?;
    let produced = &record["binding"];
    if produced["version"] != 3 {
        return Bound::of(binding);
    }
    let retained = super::macos_personalization::retained(root, &binding.bootstrap_id, &binding.target)?;
    let (a, t) = (&binding.account, &binding.target);
    if produced["keyReference"] != binding.key_reference.as_str()
        || produced["bootstrapId"] != binding.bootstrap_id.as_str()
        || produced["environmentId"] != t.environment_id.as_str()
        || produced["generation"] != t.generation.as_str()
        || produced["vmFingerprint"] != t.vm_fingerprint.as_str()
        || produced["account"]
            != json!({"gid": a.gid, "home": a.home, "homeDevice": a.home_device, "homeInode": a.home_inode,
                "name": a.short_name, "uid": a.uid})
        || produced["answerSha256"] != retained.account.bootstrap_observation_digest.as_str()
    {
        bail!("Per-guest key reference belongs to another immutable binding");
    }
    Bound::of(produced)
}
/// The retained reference, verified as the same original private file and
/// pairing, for any immutable binding. Returns the held lock and the record.
pub(super) fn resolve_in(
    root: &Path,
    key_reference: &str,
    binding: &Bound,
    verifier: &Path,
    budget: Duration,
) -> Result<(std::fs::File, Value)> {
    check_directory(root)?;
    check_directory(&root.join("macos-personalization-keys"))?;
    let path = reference_directory(root, key_reference)?;
    let guard = lock(&path)?;
    let record = read_bound(&path, binding)?;
    if record["state"] != "ready" {
        bail!(
            "Guest key generation/revocation remains fenced; original reference was not replayed"
        );
    }
    let private = path.join("private_key");
    let bytes = zeroize::Zeroizing::new(private_read(&private, 16 * 1024)?);
    let metadata = std::fs::symlink_metadata(&private)?;
    if record["receipt"]["privateSha256"] != journal::digest(&bytes)
        || record["receipt"]["device"] != metadata.dev()
        || record["receipt"]["inode"] != metadata.ino()
        || path.join("private_key-cert.pub").try_exists()?
    {
        bail!("Per-guest private key changed or gained an unapproved certificate");
    }
    if record["receipt"]["publicKey"] != derive(verifier, &private, budget)? {
        bail!("Private key no longer matches its retained public key");
    }
    Ok((guard, record))
}
#[allow(dead_code)] // Future authenticated lifecycle action; fixtures cover retained tombstones.
pub(super) fn retire(root: &Path, binding: &Binding) -> Result<()> {
    let path = directory(root, binding)?;
    let _lock = lock(&path)?;
    let mut record = read(&path, binding)?;
    record["state"] = json!("retired");
    retain(&path, &record)
}

/// Fixed OpenSSH producer. Production remains gated before any real utility or
/// credential access; no caller can supply a utility path through a control RPC.
pub(super) fn produce(root: &Path, binding: &Binding, recover: bool) -> Result<Value> {
    macos_transport::require_available()?;
    produce_using(
        root,
        binding,
        Path::new("/usr/bin/ssh-keygen"),
        recover,
        || Ok(()),
    )
}

/// A complete producer receipt, not mere key-file existence, recovers a lost
/// host reply. Unknown/partial generation is never repeated or replaced.
pub(super) fn produce_using(
    root: &Path,
    binding: &Binding,
    utility: &Path,
    recover: bool,
    after_receipt: impl FnOnce() -> Result<()>,
) -> Result<Value> {
    binding.check_retained(root)?;
    produce_in(root, &binding.key_reference, &Bound::of(binding)?, utility, recover, after_receipt)
}
fn keys_parent(root: &Path) -> Result<()> {
    check_directory(root)?;
    let parent = root.join("macos-personalization-keys");
    // A concurrent first claim may create it too; either way it is checked.
    match std::fs::DirBuilder::new().mode(0o700).create(&parent) {
        Err(error) if error.kind() != std::io::ErrorKind::AlreadyExists => return Err(error.into()),
        _ => {}
    }
    check_directory(&parent)
}
const PRODUCER: &str = "openssh-ed25519-v1";
/// Claims `key_reference` for `binding` before anything is generated, recorded
/// as `reserved`. Idempotent for the same binding, including after a crash
/// before the record was written; a reference that has any other history,
/// or another binding, stays fenced.
pub(super) fn reserve(root: &Path, key_reference: &str, binding: &Bound) -> Result<()> {
    keys_parent(root)?;
    let path = reference_directory(root, key_reference)?;
    match std::fs::DirBuilder::new().mode(0o700).create(&path) {
        Err(error) if error.kind() != std::io::ErrorKind::AlreadyExists => return Err(error.into()),
        _ => {}
    }
    let _lock = lock(&path)?;
    if path.join("record.json").try_exists()? {
        read_bound(&path, binding)?;
        return Ok(());
    }
    for entry in std::fs::read_dir(&path)? {
        if entry?.file_name() != "operation.lock" {
            bail!("Key reference has unrecorded history; it stays fenced")
        }
    }
    retain(&path, &binding.record("reserved"))
}
/// The producer for any immutable binding. A `reserved` reference is generated
/// once; an existing unknown outcome is only ever recovered from the original
/// child's receipt, and a missing reference is never recreated on recovery.
pub(super) fn produce_in(
    root: &Path,
    key_reference: &str,
    binding: &Bound,
    utility: &Path,
    recover: bool,
    after_receipt: impl FnOnce() -> Result<()>,
) -> Result<Value> {
    keys_parent(root)?;
    let path = reference_directory(root, key_reference)?;
    let existed = path.try_exists()?;
    if !existed {
        if recover {
            bail!("Original producer reference missing")
        }
        std::fs::DirBuilder::new().mode(0o700).create(&path)?;
    }
    let _guard = lock(&path)?;
    let mut record = if existed {
        read_bound(&path, binding)?
    } else {
        let value = binding.record("outcomeUnknown");
        retain(&path, &value)?;
        value
    };
    if record["producer"] != PRODUCER {
        bail!("Original operation was not this key producer")
    }
    // A reservation has never taken the producer lease or run the utility.
    let reserved = existed && record["state"] == "reserved";
    if reserved {
        for name in ["producer.lock", "private_key", "private_key.pub", "producer-receipt.json"] {
            if std::fs::symlink_metadata(path.join(name)).is_ok() {
                bail!("Reserved key reference already has producer history; it stays fenced")
            }
        }
        record["state"] = json!("outcomeUnknown");
        retain(&path, &record)?;
    } else if existed && (!recover || record["state"] != "outcomeUnknown") {
        return Ok(record);
    }
    let fresh = !existed || reserved;
    let lease = std::fs::OpenOptions::new()
        .read(true)
        .write(true)
        .create(fresh)
        .truncate(false)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(path.join("producer.lock"))?;
    let metadata = lease.metadata()?;
    // SAFETY: geteuid has no preconditions.
    if !metadata.is_file()
        || metadata.nlink() != 1
        || metadata.uid() != unsafe { libc::geteuid() }
        || metadata.mode() & 0o077 != 0
    {
        bail!("Unsafe original key producer lease")
    }
    // lease owns the fd throughout this call and the child's lifetime.
    if !crate::local_vm::journal::try_exclusive(&lease)? {
        bail!("Original key producer is still owned; no recovery or replacement")
    }
    if fresh {
        let mut command = macos_transport::isolated(utility, &path);
        command
            .args([
                "-q",
                "-t",
                "ed25519",
                "-N",
                "",
                "-C",
                "terminalx-local-vm",
                "-f",
            ])
            .arg(path.join("private_key"));
        use std::os::unix::process::CommandExt;
        let fd = lease.as_raw_fd();
        // SAFETY: only async-signal-safe libc calls in the post-fork child. The
        // inherited lock fences recovery even if the author/owner exits first.
        unsafe {
            command.pre_exec(move || {
                libc::umask(0o077);
                if libc::fcntl(fd, libc::F_SETFD, 0) == -1 {
                    return Err(std::io::Error::last_os_error());
                }
                Ok(())
            });
        }
        super::process::run(&mut command, b"", Duration::from_secs(30))?;
        let receipt = produced_pair(&path, utility)?;
        write_new(
            &path.join("producer-receipt.json"),
            &serde_json::to_vec(
                &json!({"binding":binding.value,"exit":"originalChildSuccess","receipt":receipt}),
            )?,
        )?;
        after_receipt()?;
    }
    let proof: Value = serde_json::from_slice(&private_read(
        &path.join("producer-receipt.json"),
        32 * 1024,
    )?)?;
    if proof["binding"] != binding.value
        || proof["exit"] != "originalChildSuccess"
        || proof["receipt"] != produced_pair(&path, utility)?
    {
        bail!("Original producer output/receipt changed; reference stays fenced")
    }
    record["receipt"] = proof["receipt"].clone();
    record["state"] = json!("ready");
    record["recoveredOriginalProducer"] = json!(recover);
    retain(&path, &record)?;
    Ok(record)
}
fn produced_pair(path: &Path, utility: &Path) -> Result<Value> {
    let private = path.join("private_key");
    let bytes = zeroize::Zeroizing::new(private_read(&private, 16 * 1024)?);
    if bytes.is_empty() || path.join("private_key-cert.pub").try_exists()? {
        bail!("Empty or certificate-bearing producer output")
    }
    let public_bytes = private_read(&path.join("private_key.pub"), 4096)?;
    let parts = std::str::from_utf8(&public_bytes)?
        .split_whitespace()
        .collect::<Vec<_>>();
    if parts.len() != 3 || parts[2] != "terminalx-local-vm" {
        bail!("Unexpected generated public key/comment")
    }
    let public = format!("{} {}", parts[0], parts[1]);
    super::macos_personalization::public_key(&public)?;
    if derive(utility, &private, Duration::from_secs(15))? != public {
        bail!("Generated pair differs")
    }
    let metadata = std::fs::symlink_metadata(&private)?;
    Ok(
        json!({"publicKey":public,"privateSha256":journal::digest(&bytes),"device":metadata.dev(),"inode":metadata.ino()}),
    )
}
