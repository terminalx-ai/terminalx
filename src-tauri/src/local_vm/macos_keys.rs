//! Private per-guest key lifecycle. No import-from-path API, host key discovery,
//! agent lookup or production generator exists. The future bootstrap backend
//! supplies freshly generated material through the internal producer boundary.
use super::{
    journal,
    macos_transport::{self, Binding},
};
use anyhow::{bail, Context, Result};
use serde_json::{json, Value};
use std::{
    io::{Read, Write},
    os::{
        fd::AsRawFd,
        unix::fs::{MetadataExt, OpenOptionsExt},
    },
    path::{Path, PathBuf},
    time::Duration,
};

pub(super) fn check_directory(path: &Path) -> Result<()> {
    let metadata = std::fs::symlink_metadata(path)?;
    // SAFETY: geteuid has no arguments or memory preconditions.
    if !metadata.is_dir()
        || metadata.uid() != unsafe { libc::geteuid() }
        || metadata.mode() & 0o077 != 0
    {
        bail!("Transport storage must be an owned private directory without symlinks");
    }
    Ok(())
}
pub(super) fn private_read(path: &Path, bound: u64) -> Result<Vec<u8>> {
    let file = std::fs::OpenOptions::new()
        .read(true)
        .custom_flags(libc::O_NOFOLLOW | libc::O_NONBLOCK)
        .open(path)?;
    let metadata = file.metadata()?;
    // SAFETY: geteuid has no arguments or memory preconditions.
    if !metadata.is_file()
        || metadata.nlink() != 1
        || metadata.uid() != unsafe { libc::geteuid() }
        || metadata.mode() & 0o077 != 0
    {
        bail!("Transport reference is not an owned private regular file");
    }
    let mut bytes = Vec::new();
    file.take(bound + 1).read_to_end(&mut bytes)?;
    if bytes.len() as u64 > bound {
        bail!("Private transport reference exceeds its bound");
    }
    Ok(bytes)
}
pub(super) fn write_new(path: &Path, bytes: &[u8]) -> Result<()> {
    check_directory(path.parent().context("Private reference parent missing")?)?;
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(path)?;
    file.write_all(bytes)?;
    file.sync_all()?;
    std::fs::File::open(path.parent().unwrap())?.sync_all()?;
    Ok(())
}
fn directory(root: &Path, binding: &Binding) -> Result<PathBuf> {
    journal::validate_id(&binding.key_reference)?;
    Ok(root
        .join("macos-personalization-keys")
        .join(&binding.key_reference))
}
fn lock(path: &Path) -> Result<std::fs::File> {
    check_directory(path)?;
    let lock = std::fs::OpenOptions::new()
        .write(true)
        .create(true)
        .truncate(false)
        .mode(0o600)
        .custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC)
        .open(path.join("operation.lock"))?;
    // SAFETY: lock owns its descriptor for the full preparation/RPC lifetime.
    if unsafe { libc::flock(lock.as_raw_fd(), libc::LOCK_EX | libc::LOCK_NB) } != 0 {
        bail!("Guest key reference is in use");
    }
    Ok(lock)
}
fn read(path: &Path, binding: &Binding) -> Result<Value> {
    let record: Value =
        serde_json::from_slice(&private_read(&path.join("record.json"), 32 * 1024)?)?;
    if record["binding"] != json!(binding)
        || record["inputDigest"] != journal::digest(&serde_json::to_vec(binding)?)
    {
        bail!("Per-guest key reference belongs to another immutable binding");
    }
    Ok(record)
}
#[allow(dead_code)] // The authenticated provisioning producer/retirement route is not activated.
fn retain(path: &Path, value: &Value) -> Result<()> {
    journal::atomic_private_write(&path.join("record.json"), &serde_json::to_vec(value)?)
}

/// Generated bytes are kept out of JSON, argv, logs and artifacts. A producer
/// takes no host credential path. No production source invokes this boundary.
#[allow(dead_code)] // Synthetic fixtures only until an authenticated provisioning producer exists.
pub(super) struct GeneratedKey {
    pub private: zeroize::Zeroizing<Vec<u8>>,
    pub public: String,
}
#[allow(dead_code)] // Intentionally not exposed as an import/generate control RPC.
pub(super) fn prepare_using(
    root: &Path,
    binding: &Binding,
    verifier: &Path,
    producer: impl FnOnce() -> Result<GeneratedKey>,
) -> Result<Value> {
    binding.check_retained(root)?;
    check_directory(root)?;
    let parent = root.join("macos-personalization-keys");
    if !parent.try_exists()? {
        std::fs::DirBuilder::new().mode(0o700).create(&parent)?;
    }
    check_directory(&parent)?;
    let path = directory(root, binding)?;
    if path.try_exists()? {
        let _lock = lock(&path)?;
        // Unknown, retired and ready records are observation only, not replay.
        return read(&path, binding);
    }
    std::fs::DirBuilder::new().mode(0o700).create(&path)?;
    let _lock = lock(&path)?;
    let mut record = json!({"binding":binding,"inputDigest":journal::digest(&serde_json::to_vec(binding)?),"state":"outcomeUnknown"});
    retain(&path, &record)?;
    let generated = producer()?;
    super::macos_personalization::public_key(&generated.public)?;
    if generated.private.is_empty() || generated.private.len() > 16 * 1024 {
        bail!("Generated key exceeds its bound");
    }
    let private = path.join("private_key");
    write_new(&private, &generated.private)?;
    let public = derive(verifier, &private, Duration::from_secs(15))?;
    if public != generated.public {
        bail!("Generated private/public key pairing differs");
    }
    let metadata = std::fs::symlink_metadata(&private)?;
    record["receipt"] = json!({"publicKey":public,"privateSha256":journal::digest(&generated.private),"device":metadata.dev(),"inode":metadata.ino()});
    record["state"] = json!("ready");
    retain(&path, &record)?;
    Ok(record)
}
use std::os::unix::fs::DirBuilderExt;

fn derive(program: &Path, private: &Path, budget: Duration) -> Result<String> {
    let bytes = super::process::run(
        macos_transport::isolated(program, private.parent().unwrap())
            .args(["-y", "-f"])
            .arg(private),
        b"",
        budget,
    )?;
    let public = std::str::from_utf8(&bytes)?.trim().to_string();
    super::macos_personalization::public_key(&public)?;
    Ok(public)
}
pub(super) fn resolve(
    root: &Path,
    binding: &Binding,
    verifier: &Path,
    budget: Duration,
) -> Result<std::fs::File> {
    binding.check_retained(root)?;
    check_directory(root)?;
    check_directory(&root.join("macos-personalization-keys"))?;
    let path = directory(root, binding)?;
    let guard = lock(&path)?;
    let record = read(&path, binding)?;
    if record["state"] != "ready" {
        bail!(
            "Guest key generation/revocation remains fenced; original reference was not replayed"
        );
    }
    let private = path.join("private_key");
    let bytes = zeroize::Zeroizing::new(private_read(&private, 16 * 1024)?);
    let metadata = std::fs::symlink_metadata(&private)?;
    if record["receipt"]["privateSha256"] != journal::digest(&bytes)
        || record["receipt"]["device"] != metadata.dev()
        || record["receipt"]["inode"] != metadata.ino()
        || path.join("private_key-cert.pub").try_exists()?
    {
        bail!("Per-guest private key changed or gained an unapproved certificate");
    }
    if record["receipt"]["publicKey"] != derive(verifier, &private, budget)? {
        bail!("Private key no longer matches its retained public key");
    }
    Ok(guard)
}
#[allow(dead_code)] // Future authenticated lifecycle action; fixtures cover retained tombstones.
pub(super) fn retire(root: &Path, binding: &Binding) -> Result<()> {
    let path = directory(root, binding)?;
    let _lock = lock(&path)?;
    let mut record = read(&path, binding)?;
    record["state"] = json!("retired");
    retain(&path, &record)
}
