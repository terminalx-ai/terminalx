/**
 * TerminalX's drawn icons as components, one per glyph, named as the rest of
 * the app imports them. Generated from `glyphs.ts`; edit the glyph, not this.
 */
import { createElement, forwardRef, type SVGProps } from "react";
import { GLYPHS, type Glyph } from "./glyphs";

export type IconProps = SVGProps<SVGSVGElement> & {
  /** Width and height; CSS on the element wins over it, as it does for lucide. */
  size?: number | string;
  /** Accepted for lucide compatibility; the drawn set keeps its stroke as it is. */
  absoluteStrokeWidth?: boolean;
};

const kebab = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

function icon(name: string, glyph: Glyph) {
  const Icon = forwardRef<SVGSVGElement, IconProps>(function Icon({ size = 16, strokeWidth = 1.25, className, children, absoluteStrokeWidth: _absolute, ...rest }, ref) {
    return (
      <svg
        ref={ref}
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 16 16"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        aria-hidden="true"
        className={className ? `tx-icon ${className}` : "tx-icon"}
        data-icon={kebab(name)}
        {...rest}
      >
        {glyph.map(([tag, attrs], index) => createElement(tag, { key: index, ...attrs }))}
        {children}
      </svg>
    );
  });
  Icon.displayName = name;
  return Icon;
}

